"""Build the Computation Quests website's generated pages and shared header and footer.

Usage (from the repo root):
    python tools/build_pages.py

What it does:
- Writes the Regions page (areas/index.html) and one page per region (areas/<id>/index.html)
  from REGIONS in map/build_world.py, so the site and the map never disagree.
- Adds a region's places (from its map's PLACES), its activity ideas (the table under
  "## Activity ideas" in areas/<id>/README.md), and an optional hand-written section
  (areas/<id>/extra.html) to that region's page.
- Refreshes the header and footer of the hand-written pages listed in HANDWRITTEN, between
  their <!-- header --> / <!-- /header --> and <!-- footer --> / <!-- /footer --> markers.

It needs no tile pack and draws no maps, so it runs in a second.
"""
import html
import importlib.util
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
sys.path.insert(0, os.path.join(ROOT, 'map'))
import build_world  # noqa: E402

SITE = build_world.TITLE
REPO = 'https://github.com/mrenne/csworlds'
# Where GitHub Pages will serve the site. Only 404.html uses it, because Pages shows that page
# at any missing path, so its links cannot be relative. Change it if the site moves to a
# custom domain (then it becomes '/').
BASE = '/csworlds/'

NAV = [('Map', ''), ('Regions', 'areas/'), ('About', 'about/')]
# Hand-written pages: (path from the repo root, which nav item is current)
HANDWRITTEN = [
    ('index.html', 'Map'),
    ('about/index.html', 'About'),
    ('404.html', None),
    ('areas/data-science/map/index.html', 'Regions'),
]
GENERATED = '<!-- Generated by tools/build_pages.py. Edit the region data in map/build_world.py. -->'
W, H = 872, 1252   # the overworld image


def esc(s):
    return html.escape(s, quote=True)


def prefix_for(path):
    """Relative prefix from a page to the site root ('' / '../' / ...), or BASE for 404.html."""
    if path == '404.html':
        return BASE
    return '../' * path.count('/') or './'


def header(path, current):
    p = prefix_for(path)
    items = []
    for label, href in NAV:
        cur = ' aria-current="page"' if label == current else ''
        items.append(f'<li><a href="{p}{href}"{cur}>{label}</a></li>')
    return ('<a class="skip" href="#content">Skip to content</a>\n'
            '<header class="site-header">\n  <div class="bar">\n'
            f'    <a class="brand" href="{p}">{esc(SITE)}</a>\n'
            '    <nav class="site-nav" aria-label="Site">\n'
            f'      <ul>{"".join(items)}</ul>\n'
            '    </nav>\n  </div>\n</header>')


def footer(path):
    p = prefix_for(path)
    return ('<footer class="site-footer">\n'
            f'  <p>{esc(SITE)} by Mike Renne. Free, unplugged activities: students need no technology.</p>\n'
            '  <p>Content is licensed under <a href="https://creativecommons.org/licenses/by-nc-sa/4.0/" '
            'rel="license">CC BY-NC-SA 4.0</a>. Map art is made with the La Petite Tile Maps pack, '
            f'which is not covered by that license. <a href="{p}about/#license">How to share and adapt</a>.</p>\n'
            '</footer>')


def page(path, title, current, body, description):
    p = prefix_for(path)
    return f"""<!doctype html>
{GENERATED}
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{esc(title)}</title>
<meta name="description" content="{esc(description)}">
<link rel="stylesheet" href="{p}assets/site.css">
</head>
<body>
<!-- header -->
{header(path, current)}
<!-- /header -->
{body}
<!-- footer -->
{footer(path)}
<!-- /footer -->
</body>
</html>
"""


def locator(region, prefix, alt=''):
    """A window onto the overworld image, centered on the region's banner."""
    x, y = region['banner']
    y += 40   # center a little below the banner, on the region's land
    return (f'<div class="locator" aria-hidden="{"false" if alt else "true"}">'
            f'<img src="{prefix}map/world.png" width="{W}" height="{H}" alt="{esc(alt)}" '
            f'style="left:calc(50% - {x}px);top:calc(50% - {y}px)"></div>')


def load_places(region):
    """PLACES from a region map's build script, if the region has one."""
    script = os.path.join(ROOT, 'areas', region['id'], 'map', 'build_map.py')
    if not os.path.exists(script):
        return []
    spec = importlib.util.spec_from_file_location(f'map_{region["id"].replace("-", "_")}', script)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return getattr(mod, 'PLACES', [])


def load_ideas(region):
    """Rows of the "## Activity ideas" table in the region README: (topic or place, idea, what)."""
    readme = os.path.join(ROOT, 'areas', region['id'], 'README.md')
    if not os.path.exists(readme):
        return []
    text = open(readme, encoding='utf-8').read()
    m = re.search(r'^## Activity ideas\n(.*?)(?=^## |\Z)', text, flags=re.S | re.M)
    if not m:
        return []
    rows = []
    for line in m.group(1).splitlines():
        cells = [c.strip() for c in line.strip().strip('|').split('|')]
        if len(cells) == 3 and cells[1].startswith('**'):
            rows.append((cells[0], cells[1].strip('*'), cells[2]))
    return rows


def md_inline(s):
    """Escape a table cell, keeping its **bold** and [links](url)."""
    s = esc(s)
    s = re.sub(r'\*\*(.+?)\*\*', r'<strong>\1</strong>', s)
    return re.sub(r'\[(.+?)\]\((https?://[^)\s]+)\)', r'<a href="\2">\1</a>', s)


def region_page(r):
    path = f'areas/{r["id"]}/index.html'
    p = prefix_for(path)
    places = load_places(r)
    ideas = load_ideas(r)
    extra_file = os.path.join(ROOT, 'areas', r['id'], 'extra.html')
    extra = open(extra_file, encoding='utf-8').read().strip() if os.path.exists(extra_file) else ''

    tags = []
    if r.get('start'):
        tags.append('<span class="tag">Start here</span>')
    tags.append('<span class="tag quiet">In progress</span>' if r.get('link') or extra
                else '<span class="tag quiet">Coming soon</span>')
    actions = [f'<a class="button secondary" href="{p}#{r["id"]}">Find it on the map</a>']
    if r.get('link'):
        actions.insert(0, f'<a class="button" href="{p}{r["link"]}">Open the {esc(r["name"])} map</a>')

    topics = ''.join(f'<li>{esc(t)}</li>' for t in r['topics'])
    body = [f"""<div class="intro">
  <p class="crumbs"><a href="{p}areas/">Regions</a> / {esc(r['name'])}</p>
  <h1>{esc(r['name'])}</h1>
</div>
<main id="content" class="page">
  <section class="card">
    <div class="region-head">
      <div>
        <p>{' '.join(tags)}</p>
        <p class="lede">{esc(r['text'])}</p>
        <h2>Topics</h2>
        <ul>{topics}</ul>
        <div class="actions">{''.join(actions)}</div>
      </div>
      {locator(r, p, alt=f'Where {r["name"]} lies on the map')}
    </div>
  </section>"""]

    if places:
        # A region with a map: show each place with its activity idea (matched by place name).
        by_place = {i[0]: i for i in ideas}
        items = []
        for pl in places:
            idea = by_place.get(pl['name'])
            note = (f'<p class="idea-text"><strong>Activity idea: {esc(idea[1])}.</strong> {md_inline(idea[2])}</p>'
                    if idea else '')
            items.append(f'<li><span class="tag quiet">{esc(pl["step"])}</span>'
                         f'<a href="{p}{r["link"]}#{pl["id"]}">{esc(pl["name"])}</a>{note}</li>')
        body.append(f"""  <section class="card">
    <h2>Places and activity ideas</h2>
    <p class="muted">Each place on the {esc(r['name'])} map is one step of the journey, with an
      unplugged activity idea. Select a place to open it on the map.</p>
    <ul class="places">{''.join(items)}</ul>
  </section>""")
    elif ideas:
        items = ''.join(f'<li><strong>{esc(name)}</strong> <span class="muted">· {esc(topic)}</span>'
                        f'<p class="idea-text">{md_inline(what)}</p></li>' for topic, name, what in ideas)
        body.append(f"""  <section class="card">
    <h2>Activity ideas</h2>
    <p class="muted">Unplugged ideas for each topic, to be written up as full activities.</p>
    <ul class="places">{items}</ul>
  </section>""")

    if extra:
        body.append(f'  <section class="card">\n{extra}\n  </section>')

    body.append("""  <section class="card">
    <h2>Activities</h2>
    <p>Full activities for this region are being written. Each will be unplugged, with a teacher
      guide and print-ready handouts, and students will need no technology.</p>
  </section>
</main>""")
    desc = f'{r["name"]} on {SITE}: {r["text"]}'
    return path, page(path, f'{r["name"]} | {SITE}', 'Regions', '\n'.join(body), desc)


def regions_index():
    path = 'areas/index.html'
    p = prefix_for(path)
    # Suggested order: the starting point first, the center last.
    order = sorted(build_world.REGIONS, key=lambda r: (not r.get('start'), r['id'] == 'ethics-and-impacts'))
    cards = []
    for r in order:
        status = 'In progress' if r.get('link') else 'Coming soon'
        tag = '<span class="tag">Start here</span> ' if r.get('start') else ''
        cards.append(f"""  <a class="region-card" href="{r['id']}/">
    {locator(r, p)}
    <div class="body">
      <p>{tag}<span class="tag quiet">{status}</span></p>
      <h2>{esc(r['name'])}</h2>
      <p>{esc(r['text'])}</p>
    </div>
  </a>""")
    body = f"""<div class="intro">
  <h1>Regions</h1>
  <p>Each region of the map covers one area of computer science. Begin with Computational
    Thinking; every road leads to Ethics and Impacts.</p>
</div>
<main id="content" class="region-grid">
{chr(10).join(cards)}
</main>"""
    return path, page(path, f'Regions | {SITE}', 'Regions', body,
                      f'The regions of {SITE}, one for each area of computer science.')


def refresh_chrome(path, current):
    full = os.path.join(ROOT, path)
    text = open(full, encoding='utf-8').read()
    new = re.sub(r'<!-- header -->.*?<!-- /header -->',
                 lambda m: f'<!-- header -->\n{header(path, current)}\n<!-- /header -->', text, flags=re.S)
    new = re.sub(r'<!-- footer -->.*?<!-- /footer -->',
                 lambda m: f'<!-- footer -->\n{footer(path)}\n<!-- /footer -->', new, flags=re.S)
    if '<!-- header -->' not in text or '<!-- footer -->' not in text:
        print(f'warning: {path} has no header or footer markers')
    if new != text:
        with open(full, 'w', encoding='utf-8', newline='\n') as f:
            f.write(new)


def main():
    pages = [regions_index()] + [region_page(r) for r in build_world.REGIONS]
    for path, text in pages:
        full = os.path.join(ROOT, path)
        os.makedirs(os.path.dirname(full), exist_ok=True)
        with open(full, 'w', encoding='utf-8', newline='\n') as f:
            f.write(text)
    for path, current in HANDWRITTEN:
        refresh_chrome(path, current)
    print(f'{len(pages)} pages written, {len(HANDWRITTEN)} headers and footers refreshed')


if __name__ == '__main__':
    main()
